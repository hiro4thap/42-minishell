#include "libft.h"

// Returns 1 if c is in [a..z], [A..Z], 0 otherwise.
int	ft_isalpha(int c)
{
	if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z'))
		return (1);
	return (0);
}
